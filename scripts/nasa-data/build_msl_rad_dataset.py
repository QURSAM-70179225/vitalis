#!/usr/bin/env python3
"""
Builds VITALIS's real-radiation dataset from NASA Curiosity (MSL) RAD cruise measurements.

Input : scripts/nasa-data/raw/*.csv   (from fetch_msl_rad_cruise.sh: utc,doseB,doseE in µGy/h)
Output: data/nasa/msl_rad_cruise_observations.csv  every observation (time, dose rates)
        data/nasa/msl_rad_cruise_daily.csv          one row per day (what the app uses)
        src/data/nasa/mslRadCruise.ts               the same daily values as a TypeScript module

Measured values (from NASA): absorbed dose rate of the E detector (tissue-like plastic), µGy/h.
Derived values (by VITALIS, clearly labelled):
  absorbed_mGy_per_day      = mean dose rate of the day × 24 / 1000
  dose_equivalent_mSv_day   = estimate for crew dose equivalent:
      background part × 3.82  (cruise average quality factor: 1.84 mSv/day ÷ 0.481 mGy/day, Zeitlin et al. 2013)
      solar-storm excess × 1.5 (assumed quality factor for proton-dominated solar particle radiation)
  Background = median of all daily absorbed doses (quiet-Sun level).
  solar_event = day's absorbed dose ≥ 1.5 × background.
"""
import csv, datetime, glob, os, statistics

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RAW = os.path.join(ROOT, 'scripts', 'nasa-data', 'raw')
Q_GCR, Q_SEP = 3.82, 1.5

obs = []
for f in sorted(glob.glob(os.path.join(RAW, '*.csv'))):
    for row in csv.reader(open(f)):
        if len(row) != 3:
            continue
        t, b, e = row
        try:
            b, e = float(b), float(e)
        except ValueError:
            continue
        if e <= 0:
            continue  # instrument off / no integration
        y, rest = t.split('-', 1)
        doy, hms = rest.split()
        d = datetime.date(int(y), 1, 1) + datetime.timedelta(int(doy) - 1)
        obs.append((datetime.datetime.combine(d, datetime.time.fromisoformat(hms)), b, e))
obs.sort()

os.makedirs(os.path.join(ROOT, 'data', 'nasa'), exist_ok=True)
with open(os.path.join(ROOT, 'data', 'nasa', 'msl_rad_cruise_observations.csv'), 'w', newline='') as fh:
    w = csv.writer(fh)
    w.writerow(['utc', 'dose_rate_B_uGy_per_h', 'dose_rate_E_uGy_per_h'])
    for t, b, e in obs:
        w.writerow([t.isoformat() + 'Z', f'{b:.5f}', f'{e:.5f}'])

days = {}
for t, b, e in obs:
    days.setdefault(t.date(), []).append(e)
absorbed = {d: statistics.fmean(v) * 24 / 1000 for d, v in days.items()}
background = statistics.median(absorbed.values())

rows = []
for d in sorted(days):
    a = absorbed[d]
    excess = max(0.0, a - background)
    eq = min(a, background) * Q_GCR + excess * Q_SEP
    rows.append({
        'date': d.isoformat(),
        'day_of_year': d.timetuple().tm_yday,
        'observations': len(days[d]),
        'mean_dose_rate_E_uGy_per_h': round(statistics.fmean(days[d]), 3),
        'median_dose_rate_E_uGy_per_h': round(statistics.median(days[d]), 3),
        'max_dose_rate_E_uGy_per_h': round(max(days[d]), 3),
        'absorbed_mGy_per_day': round(a, 4),
        'dose_equivalent_mSv_per_day_est': round(eq, 3),
        'solar_event': 'yes' if a >= 1.5 * background else 'no',
    })

with open(os.path.join(ROOT, 'data', 'nasa', 'msl_rad_cruise_daily.csv'), 'w', newline='') as fh:
    w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
    w.writeheader()
    w.writerows(rows)

ts = os.path.join(ROOT, 'src', 'data', 'nasa', 'mslRadCruise.ts')
with open(ts, 'w') as fh:
    fh.write('''/**
 * REAL NASA DATA, generated by scripts/nasa-data/build_msl_rad_dataset.py — do not edit by hand.
 *
 * Daily radiation measured by the Radiation Assessment Detector (RAD) aboard NASA's Curiosity
 * rover (Mars Science Laboratory) while it flew from Earth to Mars, 6 Dec 2011 – 14 Jul 2012.
 * Source: NASA Planetary Data System, PPI node, data set MSL-M-RAD-3-RDR-V1.0 (CRUISE).
 *   https://pds-ppi.igpp.ucla.edu/data/MSL-M-RAD-3-RDR-V1.0/
 * Citation: Hassler, D. M. et al., MSL RAD Reduced Data Records, NASA PDS (2013);
 *   Zeitlin, C. et al., Science 340, 1080 (2013), doi:10.1126/science.1235989.
 *
 * Fields: d = UTC date, n = observations that day, a = absorbed dose (mGy/day, measured),
 *   q = crew dose-equivalent estimate (mSv/day, derived — see data/nasa/README.md), s = solar event day.
 * Background (quiet Sun) absorbed dose: %.4f mGy/day.
 */
export interface RadDay {
  d: string;
  n: number;
  a: number;
  q: number;
  s: boolean;
}

export const MSL_RAD_SOURCE = {
  name: 'NASA Curiosity (MSL) Radiation Assessment Detector — cruise to Mars',
  dataset: 'MSL-M-RAD-3-RDR-V1.0',
  archive: 'NASA Planetary Data System (PPI node)',
  url: 'https://pds-ppi.igpp.ucla.edu/data/MSL-M-RAD-3-RDR-V1.0/',
  from: '%s',
  to: '%s',
  days: %d,
  observations: %d,
  backgroundMgyPerDay: %.4f,
} as const;

export const MSL_RAD_CRUISE: RadDay[] = [
''' % (background, rows[0]['date'], rows[-1]['date'], len(rows), len(obs), background))
    for r in rows:
        fh.write("  { d: '%s', n: %d, a: %s, q: %s, s: %s },\n" % (r['date'], r['observations'], r['absorbed_mGy_per_day'], r['dose_equivalent_mSv_per_day_est'], 'true' if r['solar_event'] == 'yes' else 'false'))
    fh.write('];\n')

print(f'{len(obs)} observations, {len(rows)} days, background {background:.4f} mGy/day '
      f'≈ {background * Q_GCR:.2f} mSv/day; solar-event days: {[r["date"] for r in rows if r["solar_event"] == "yes"]}')
